import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const url = process.env.RRP_LAB_URL || 'http://127.0.0.1:5186/reality-lab.html';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage(), errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message)); page.on('request', request => requests.push(request.url()));
  await page.goto(url); await page.locator('#version').waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('#loss').fill('0');
  await page.locator('#hypothesis').fill('Host故障時の停止と復旧を確認');
  await page.locator('#compare').click();
  await page.waitForFunction(() => document.querySelectorAll('.card').length === 3, undefined, { timeout: 45000 });
  assert.match(await page.locator('#results').innerText(), /open \/ 2/);
  assert.match(await page.locator('#events').innerText(), /再接続/);
  await page.locator('#observation').fill('停止とCheckpointへの巻戻しが数値に出る。');
  await page.locator('#seed').fill('123');
  await page.locator('#hypothesis').fill('未実行の次の仮説');
  await page.locator('#save').click();
  assert.match(await page.locator('#history').innerText(), /Host故障時/);
  assert.doesNotMatch(await page.locator('#history').innerText(), /未実行/);
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem(Object.keys(localStorage).find(k => k.includes('rrp-lab'))))[0]);
  assert.equal(stored.config.seed, 20260916); assert.equal(stored.results.length, 3);
  assert.match(stored.evidence.transport, /in-process/);
  await page.locator('#discussion').click();
  assert.match(await page.locator('#handoff').inputValue(), /次の仮説/);
  assert.match(await page.locator('#handoff').inputValue(), /計算|payload/);
  const downloaded = page.waitForEvent('download'); await page.locator('#export').click();
  const download = await downloaded; assert.match(download.suggestedFilename(), /rrp-20260916-host/);
  const file = await download.path();
  await page.locator('#import').setInputFiles(file);
  assert.equal(await page.locator('#seed').inputValue(), '20260916');
  await page.reload();
  assert.match(await page.locator('#history').innerText(), /Host故障時/);
  await page.locator('#history button').first().click();
  await page.locator('#scenario').selectOption('divergence'); await page.locator('#durationMs').selectOption('16000');
  await page.locator('#compare').click();
  await page.waitForFunction(() => document.querySelectorAll('.card').length === 3, undefined, { timeout: 45000 });
  assert.match(await page.locator('#events').innerText(), /checksum不一致/);
  assert.match(await page.locator('#events').innerText(), /再同期データ/);
  if (process.env.RRP_LAB_SCREENSHOT) await page.screenshot({ path: process.env.RRP_LAB_SCREENSHOT, fullPage: true });
  await page.locator('#play').click(); assert.equal(await page.locator('#conditions').isDisabled(), true);
  await page.locator('#stop').click(); assert.equal(await page.locator('#save').isDisabled(), true);
  await page.locator('#import').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"format":"wrong"}') });
  assert.match(await page.locator('#status').innerText(), /読み込めません/);
  assert.deepEqual(errors, []);
  assert.equal(requests.some(request => /\.(glb|gltf|ktx2|vrm|mp3|ogg)(\?|$)/.test(request)), false);
  console.log(JSON.stringify({ browser: 'Chromium', viewport: '390x844', checks: ['no horizontal overflow', '30 modeled peers / host kill / epoch 2 / reconnect', 'captured-config persistence', 'discussion text', 'JSON export/import', 'history reload', 'corruption repair', 'cancellation', 'invalid import', 'no 3D/audio asset requests'], pageErrors: errors.length }));
} finally { await browser.close(); }
